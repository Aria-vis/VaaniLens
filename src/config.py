"""Global configuration parameters for VaaniLens."""

# Standard operating system interface for inspecting runtime environment flags
import os

# Check whether offline execution mode has been requested by the user or container environment
# When VAANI_OFFLINE is set to '1', network requests to Hugging Face Hub are completely disabled
if os.environ.get("VAANI_OFFLINE") == "1":
    # Instruct huggingface_hub to operate strictly from local cache directory
    os.environ.setdefault("HF_HUB_OFFLINE", "1")
    # Instruct transformers library to prevent any remote weight verification or downloads
    os.environ.setdefault("TRANSFORMERS_OFFLINE", "1")

# Human-in-the-loop oversight threshold: any prediction with posterior confidence < 0.75 triggers an amber review banner
CONF_THRESHOLD = 0.75

# Number of local synthetic perturbation samples generated by LIME text explainer
# Balanced at 200 to achieve statistically robust feature attribution within ~1-2 seconds on laptop CPU
LIME_SAMPLES = 200

# Maximum token sequence length passed to tokenizers to avoid out-of-memory errors on extreme-length inputs
MAX_TOKENS = 256

# Global pseudo-random seed used across dataset splits, model training, and LIME perturbation generation
RANDOM_STATE = 42


